use ratatui::layout::{Constraint, Flex, Layout, Rect};

pub fn center(area: Rect, h: Constraint, v: Constraint) -> Rect {
    let [area] = Layout::horizontal([h])
        .flex(Flex::Center)
        .areas(area);
    let [area] = Layout::vertical([v]).flex(Flex::Center).areas(area);
    area
}

